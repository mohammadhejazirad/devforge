"""Shell integration and executable shims.

The rc block is marked and can be removed without touching the rest of the
file. Shims honor a project pin, then a DevForge default, and refuse a version
string that could be a flag or a path.
"""

from __future__ import annotations

import re
from pathlib import Path

BEGIN = "# >>> devforge initialize >>>"
END = "# <<< devforge initialize <<<"

_SAFE_PREFIX = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]{0,40}$")


def rc_targets(home: Path, shell_name: str) -> list[tuple[str, Path]]:
    """Rc files to update. Existing files are included, plus the current shell."""
    candidates = [
        ("sh", home / ".bashrc"),
        ("sh", home / ".zshrc"),
        ("fish", home / ".config" / "fish" / "config.fish"),
    ]
    selected: list[tuple[str, Path]] = []
    for kind, path in candidates:
        if path.is_file():
            selected.append((kind, path))
    if selected:
        return selected
    if "fish" in shell_name:
        return [("fish", home / ".config" / "fish" / "config.fish")]
    if "zsh" in shell_name:
        return [("sh", home / ".zshrc")]
    return [("sh", home / ".bashrc")]


def render_block(kind: str, shims: Path) -> str:
    quoted = sh_single(str(shims))
    fish = f"set -gx PATH {quoted} $PATH"
    posix = f"export PATH={quoted}:$PATH"
    body = fish if kind == "fish" else posix
    return f"{BEGIN}\n{body}\n{END}\n"


def upsert_block(existing: str, block: str) -> str:
    """Insert or replace the managed block."""
    begin = existing.find(BEGIN)
    end = existing.find(END)
    if begin != -1 and end != -1 and end > begin:
        suffix_at = end + len(END)
        if existing[suffix_at : suffix_at + 1] == "\n":
            suffix_at += 1
        return existing[:begin] + block + existing[suffix_at:]
    if existing and not existing.endswith("\n"):
        existing += "\n"
    return existing + "\n" + block


def remove_block(existing: str) -> str:
    begin = existing.find(BEGIN)
    end = existing.find(END)
    if begin == -1 or end == -1 or end < begin:
        return existing
    suffix_at = end + len(END)
    if existing[suffix_at : suffix_at + 1] == "\n":
        suffix_at += 1
    updated = existing[:begin] + existing[suffix_at:]
    return updated.replace("\n\n\n", "\n\n")


def render_env(assignments: dict[str, str]) -> str:
    """A sourced fragment. Names and values are checked by the mirror loader."""
    lines = ["# Generated by DevForge. Do not edit.", ""]
    for name in sorted(assignments):
        lines.append(f"export {name}={sh_single(assignments[name])}")
    lines.append("")
    return "\n".join(lines)


def render_shim(
    *,
    binary: str,
    tool: str,
    root: Path,
    env_file: Path,
    project_files: tuple[str, ...],
    system_bins: tuple[str, ...],
    shim_kind: str,
    runtime_env: tuple[tuple[str, str], ...],
) -> str:
    """Return a POSIX shim. ``binary`` and the templates come from the catalog."""
    if _SAFE_PREFIX.fullmatch(binary) is None or _SAFE_PREFIX.fullmatch(tool) is None:
        raise ValueError(f"refusing unsafe shim name {binary!r}")
    pins = [name for name in project_files if _safe_filename(name)]
    pin_loop = "\n".join(
        f"""        if [ -f "$dir"/{sh_single(name)} ]; then
            ver=$(tr -d '[:space:]' < "$dir"/{sh_single(name)})
            break
        fi"""
        for name in pins
    )
    system_lines = []
    for template in system_bins:
        if not re.fullmatch(r"[A-Za-z0-9._+-]*(\{mm\}|\{compact\}|\{major\})?", template):
            raise ValueError(f"refusing unsafe system binary template {template!r}")
        command = (
            template.replace("{mm}", "$mm")
            .replace("{compact}", "$compact")
            .replace("{major}", "$major")
        )
        system_lines.append(
            f'if command -v "{command}" >/dev/null 2>&1; then\n    exec "{command}" "$@"\nfi'
        )
    system_block = "\n".join(system_lines)
    env_lines = []
    for key, value in runtime_env:
        if _SAFE_PREFIX.fullmatch(key) is None:
            raise ValueError(f"refusing unsafe environment name {key!r}")
        if value != "{prefix}":
            raise ValueError(f"refusing runtime env value {value!r}")
        env_lines.append(f'{key}="$ROOT/$ver"\nexport {key}')
    runtime_block = "\n".join(env_lines)
    if shim_kind == "phar":
        launch = 'exec php "$ROOT/$ver/composer.phar" "$@"'
    else:
        launch = f"""if [ -x "$ROOT/$ver/bin/{binary}" ]; then
    {runtime_block}
    exec "$ROOT/$ver/bin/{binary}" "$@"
fi
if [ -x "$ROOT/$ver/{binary}" ]; then
    {runtime_block}
    exec "$ROOT/$ver/{binary}" "$@"
fi
{system_block}"""
    env_name = re.sub(r"[^A-Z0-9]", "_", tool.upper())
    awk_line = (
        "            ver=$(awk -v key="
        + sh_single(tool)
        + " '$1 == key { print $2; exit }' \"$dir/.tool-versions\")"
    )
    return f"""#!/bin/sh
# DevForge shim for {binary}. Regenerated by DevForge.
set -eu
ROOT={sh_single(str(root))}
ENV_FILE={sh_single(str(env_file))}
if [ -f "$ENV_FILE" ]; then
    # shellcheck disable=SC1090
    . "$ENV_FILE"
fi
ver=${{DEVFORGE_{env_name}_VERSION:-}}
if [ -z "$ver" ]; then
    dir=$(pwd)
    while [ "$dir" != "/" ]; do
{pin_loop}
        if [ -n "$ver" ]; then
            break
        fi
        if [ -f "$dir/.tool-versions" ]; then
{awk_line}
            if [ -n "$ver" ]; then
                break
            fi
        fi
        dir=$(dirname "$dir")
    done
fi
if [ -z "$ver" ] && [ -f "$ROOT/default" ]; then
    ver=$(tr -d '[:space:]' < "$ROOT/default")
fi
case "$ver" in
    "" | *[!0-9A-Za-z._+-]* | [-]*)
        echo "devforge: no valid {binary} version is selected" >&2
        exit 1
        ;;
esac
mm=$(printf '%s\\n' "$ver" | cut -d. -f1,2)
compact=$(printf '%s\\n' "$mm" | tr -d '.')
major=$(printf '%s\\n' "$ver" | cut -d. -f1)
{launch}
echo "devforge: {binary} $ver is not installed" >&2
exit 1
"""


def sh_single(value: str) -> str:
    """Quote ``value`` for a POSIX single-quoted string."""
    return "'" + value.replace("'", "'\\''") + "'"


def _safe_filename(name: str) -> bool:
    return bool(re.fullmatch(r"\.[A-Za-z0-9][A-Za-z0-9._-]{0,40}", name))
